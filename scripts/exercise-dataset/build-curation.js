#!/usr/bin/env node
/**
 * Writes the exercise library's curation, from curate.js (never at app run time):
 *   node scripts/exercise-dataset/build-curation.js
 * - src/core/db/migrations/0005_exercise_curation.sql: the dataset names fixed, a built-in's movement on
 *   other equipment given its primary muscle, and the dropped dataset exercises hidden, except any used
 *   in a workout, a routine or a favourite, which stay and rank last.
 * - src/features/exercises/domain/catalogue.generated.ts: each kept exercise's search rank and the names
 *   search finds it by.
 * Reads the library as migrations 0001 and 0004 seed it, so it needs nothing outside this repo.
 */
const fs = require('node:fs');
const path = require('node:path');

const { FAMILIES, curate, familyTerms } = require('./curate');

const ROOT = path.resolve(__dirname, '../..');
const MIGRATIONS = path.join(ROOT, 'src/core/db/migrations');
const BUILT_INS_SQL = path.join(MIGRATIONS, '0001_workout_model.sql');
const DATASET_SQL = path.join(MIGRATIONS, '0004_exercise_dataset.sql');
const MIGRATION = path.join(MIGRATIONS, '0005_exercise_curation.sql');
const CATALOGUE = path.join(ROOT, 'src/features/exercises/domain/catalogue.generated.ts');
const CURATED_AT = '2026-10-04T00:00:00.000Z';
const MUSCLES = [
  'chest',
  'lats',
  'upper_back',
  'lower_back',
  'shoulders',
  'traps',
  'biceps',
  'triceps',
  'forearms',
  'abs',
  'quads',
  'hamstrings',
  'glutes',
  'calves',
  'adductors',
  'abductors',
];

const unquote = (text) => text.replace(/''/g, "'");
const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

/** The built-in exercises, as migration 0001 seeds them. */
function builtIns() {
  const sql = fs.readFileSync(BUILT_INS_SQL, 'utf8');
  const rows = [
    ...sql.matchAll(
      /\('([a-z0-9-]+)', NULL, [^,]+, [^,]+, NULL, 0, '((?:[^']|'')*)', '([a-z_]+)', '([a-z_]+)', '(\[[^\]]*\])', '[a-z]+', \d, \d\)/g,
    ),
  ];
  if (rows.length === 0) throw new Error(`No seeded exercises found in ${BUILT_INS_SQL}`);
  return rows.map((match) => ({
    id: match[1],
    name: unquote(match[2]),
    equipment: match[3],
    primaryMuscle: match[4],
    secondaryMuscles: JSON.parse(match[5]),
  }));
}

/** One of migration 0004's code tables: `muscle` -> { a: 'chest', ... }. */
function codes(sql, table) {
  const line = sql.match(new RegExp(`\`${table}\`\\(\`code\`, \`value\`\\) AS \\(VALUES ([^\\n]*)\\)`));
  if (!line) throw new Error(`No ${table} codes in ${DATASET_SQL}`);
  return Object.fromEntries(
    [...line[1].matchAll(/\('([a-z])','([a-z_]+)'\)/g)].map((match) => [match[1], match[2]]),
  );
}

/** The dataset's exercises, as migration 0004 seeds them. */
function imported() {
  const sql = fs.readFileSync(DATASET_SQL, 'utf8');
  const muscle = codes(sql, 'muscle');
  const equipment = codes(sql, 'equipment');
  const rows = [
    ...sql.matchAll(/\('([a-z0-9-]+)','((?:[^']|'')*)','([a-z])','([a-z])','([a-z]*)','[a-z]',[01]\)/g),
  ];
  if (rows.length === 0) throw new Error(`No seeded exercises found in ${DATASET_SQL}`);
  return rows.map((match) => ({
    id: match[1],
    name: unquote(match[2]),
    equipment: equipment[match[3]],
    primaryMuscle: muscle[match[4]],
    secondaryMuscles: [...match[5]].map((code) => muscle[code]),
  }));
}

const byMuscleOrder = (muscles) => [...muscles].sort((a, b) => MUSCLES.indexOf(a) - MUSCLES.indexOf(b));
const values = (rows) => rows.map((row) => `(${row.map(quote).join(',')})`).join(',\n');

/** The migration: three statements, none touching a row a person made themselves (`is_custom`). */
function migration(kept, dropped, total) {
  const renamed = kept.filter((entry) => !entry.builtIn && entry.newName !== entry.name);
  const aligned = kept.filter((entry) => entry.newPrimaryMuscle);
  const secondary = (entry) => JSON.stringify(byMuscleOrder(entry.newSecondaryMuscles));
  return [
    '-- Generated by scripts/exercise-dataset/build-curation.js from curate.js: do not edit by hand.',
    `-- Curates the ${total} exercises for search: ${kept.length} kept, ${dropped.length} dropped (near-duplicates,`,
    '-- stretches, combos, misnamed and specialised records). Ids never change; custom exercises are not touched.',
    `-- 1. Dropped: ${dropped.length} dataset exercises hidden, unless a workout, a routine or a favourite uses one.`,
    '--    First, so a near-duplicate is gone before the one kept takes the name they share.',
    'WITH `dropped`(`id`) AS (VALUES',
    values(dropped.map((entry) => [entry.id])),
    ')',
    `UPDATE \`exercises\` SET \`deleted_at\` = '${CURATED_AT}', \`updated_at\` = '${CURATED_AT}'`,
    'WHERE `is_custom` = 0 AND `deleted_at` IS NULL AND `id` IN (SELECT `id` FROM `dropped`)',
    'AND `id` NOT IN (SELECT `exercise_id` FROM `workout_exercises`)',
    'AND `id` NOT IN (SELECT `exercise_id` FROM `routine_exercises`)',
    'AND `id` NOT IN (SELECT `exercise_id` FROM `exercise_favourites`);',
    '--> statement-breakpoint',
    `-- 2. Names: ${renamed.length} dataset names fixed ("One Arm" -> "Single Arm", "Revers" -> "Reverse"), unless`,
    '--    the new name is already another exercise in the library.',
    'WITH `renamed`(`id`, `name`) AS (VALUES',
    values(renamed.map((entry) => [entry.id, entry.newName])),
    ')',
    'UPDATE `exercises`',
    `SET \`name\` = (SELECT r.\`name\` FROM \`renamed\` AS r WHERE r.\`id\` = \`exercises\`.\`id\`), \`updated_at\` = '${CURATED_AT}'`,
    'WHERE `is_custom` = 0 AND `id` IN (SELECT `id` FROM `renamed`)',
    'AND NOT EXISTS (SELECT 1 FROM `renamed` AS r JOIN `exercises` AS other ON lower(other.`name`) = lower(r.`name`)',
    '  WHERE r.`id` = `exercises`.`id` AND other.`id` <> `exercises`.`id` AND other.`deleted_at` IS NULL);',
    '--> statement-breakpoint',
    `-- 3. Muscles: ${aligned.length} dataset exercises that are a built-in's movement on other equipment take its`,
    '--    primary muscle (dumbbell squats: quads, as for the barbell squat); the old one becomes a secondary one.',
    'WITH `aligned`(`id`, `primary`, `secondary`) AS (VALUES',
    values(aligned.map((entry) => [entry.id, entry.newPrimaryMuscle, secondary(entry)])),
    ')',
    'UPDATE `exercises` SET',
    '  `primary_muscle` = (SELECT a.`primary` FROM `aligned` AS a WHERE a.`id` = `exercises`.`id`),',
    '  `secondary_muscles` = (SELECT a.`secondary` FROM `aligned` AS a WHERE a.`id` = `exercises`.`id`),',
    `  \`updated_at\` = '${CURATED_AT}'`,
    'WHERE `is_custom` = 0 AND `id` IN (SELECT `id` FROM `aligned`);',
    '',
  ].join('\n');
}

const literal = (value) => JSON.stringify(value).replace(/'/g, "\\'").replace(/"/g, "'");

/** The catalogue the app ranks search by: the families once, then one short entry per exercise. */
function catalogue(kept) {
  const familyIndex = new Map(FAMILIES.map((family, index) => [family.id, index]));
  const families = FAMILIES.map((family) => {
    const related = familyTerms(family.id).filter((term) => !family.ids.flat().includes(term));
    return `    { names: ${literal(family.ids)}, related: ${literal(related)} },`;
  });
  const ordered = [...kept].sort((a, b) => a.rank - b.rank);
  const exercises = ordered.map((entry) => {
    const family = entry.family === null ? -1 : familyIndex.get(entry.family);
    return `    '${entry.id}': [${entry.rank}, ${family}, ${entry.identity}, ${entry.modifiers.length === 0 ? 1 : 0}],`;
  });
  const aliases = ordered
    .filter((entry) => entry.aliases.length > 0)
    .map((entry) => `    '${entry.id}': ${literal(entry.aliases)},`);
  return [
    '// Generated by scripts/exercise-dataset/build-curation.js from curate.js: do not edit by hand.',
    "import type { CatalogueData } from './catalogue';",
    '',
    'export const CATALOGUE: CatalogueData = {',
    '  families: [',
    ...families,
    '  ],',
    '  exercises: {',
    ...exercises,
    '  },',
    '  aliases: {',
    ...aliases,
    '  },',
    '};',
    '',
  ].join('\n');
}

function main() {
  const library = builtIns();
  const dataset = imported();
  const { kept, dropped } = curate(library, dataset);
  const unranked = kept.filter((entry) => entry.rank === undefined);
  if (unranked.length > 0)
    throw new Error(`Unranked exercises: ${unranked.map((entry) => entry.id).join(', ')}`);
  fs.writeFileSync(MIGRATION, migration(kept, dropped, library.length + dataset.length));
  fs.writeFileSync(CATALOGUE, catalogue(kept));
  process.stdout.write(
    `${library.length} built-ins + ${dataset.length} dataset -> ${kept.length} kept, ${dropped.length} dropped\n` +
      `wrote ${path.relative(ROOT, MIGRATION)} and ${path.relative(ROOT, CATALOGUE)}\n`,
  );
}

// Run by hand; the tests require it to check the committed files are what it writes.
if (require.main === module) main();

module.exports = { CATALOGUE, MIGRATION, builtIns, catalogue, imported, migration };
