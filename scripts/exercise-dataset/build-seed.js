#!/usr/bin/env node
/**
 * Writes src/core/db/migrations/0004_exercise_dataset.sql from the open exercise dataset, through map.js.
 * Run by hand when the dataset changes (never at app run time):
 *   node scripts/exercise-dataset/build-seed.js [path/to/exercises.json]
 * Default path: ../exercises-dataset/data/exercises.json (a clone beside this repo).
 * Only the fields the app uses are kept; instructions and the dataset's media are left out.
 */
const fs = require('node:fs');
const path = require('node:path');

const { mapDataset } = require('./map');

const ROOT = path.resolve(__dirname, '../..');
const SOURCE = path.resolve(process.argv[2] ?? path.join(ROOT, '../exercises-dataset/data/exercises.json'));
const LIBRARY_SQL = path.join(ROOT, 'src/core/db/migrations/0001_workout_model.sql');
const OUTPUT = path.join(ROOT, 'src/core/db/migrations/0004_exercise_dataset.sql');
const SEEDED_AT = '2026-10-04T00:00:00.000Z';

const MUSCLES = new Set([
  'chest',
  'lats',
  'upper_back',
  'lower_back',
  'shoulders',
  'traps',
  'biceps',
  'triceps',
  'forearms',
  'abs',
  'quads',
  'hamstrings',
  'glutes',
  'calves',
  'adductors',
  'abductors',
]);
const EQUIPMENT = new Set(['barbell', 'dumbbell', 'machine', 'cable', 'bodyweight', 'kettlebell', 'band']);
const TYPES = new Set(['weighted', 'bodyweight', 'timed']);

/** One letter per value, so each seeded row stays short. Muscles in MUSCLES order: a = chest ... p. */
const MUSCLE_CODE = Object.fromEntries(
  [...MUSCLES].map((muscle, index) => [muscle, 'abcdefghijklmnop'[index]]),
);
const EQUIPMENT_CODE = Object.fromEntries([...EQUIPMENT].map((item, index) => [item, 'bdmcwkr'[index]]));
const TYPE_CODE = { weighted: 'w', bodyweight: 'b', timed: 't' };

/** The library's built-in exercises, as migration 0001 seeds them: the ones the dataset must not repeat. */
function existingLibrary() {
  const sql = fs.readFileSync(LIBRARY_SQL, 'utf8');
  const rows = [...sql.matchAll(/\('([a-z0-9-]+)', NULL, [^,]+, [^,]+, NULL, 0, '((?:[^']|'')*)'/g)];
  if (rows.length === 0) throw new Error(`No seeded exercises found in ${LIBRARY_SQL}`);
  return rows.map((match) => ({ id: match[1], name: match[2].replace(/''/g, "'") }));
}

/** Fails loudly on a row the app could not read, rather than seeding it. */
function check(exercise) {
  const problems = [];
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(exercise.id)) problems.push('id');
  if (!exercise.name) problems.push('name');
  if (!EQUIPMENT.has(exercise.equipment)) problems.push('equipment');
  if (!MUSCLES.has(exercise.primaryMuscle)) problems.push('primary muscle');
  if (!exercise.secondaryMuscles.every((muscle) => MUSCLES.has(muscle))) problems.push('secondary muscles');
  if (!TYPES.has(exercise.type)) problems.push('type');
  if (problems.length > 0) {
    throw new Error(`Malformed exercise ${JSON.stringify(exercise)}: ${problems.join(', ')}`);
  }
}

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

function main() {
  const records = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
  if (!Array.isArray(records)) throw new Error(`${SOURCE} is not an array of exercises`);
  const { added, duplicates, skipped } = mapDataset(records, existingLibrary());
  added.forEach(check);
  const skippedTotal = Object.values(skipped).reduce((sum, count) => sum + count, 0);

  // Compact: each row carries only what differs (id, name, one-letter codes); the codes, the seed date
  // and the fixed columns are spelled out once below. Same rows in the database as the long form.
  const values = added.map(
    (exercise) =>
      `(${[
        quote(exercise.id),
        quote(exercise.name),
        quote(EQUIPMENT_CODE[exercise.equipment]),
        quote(MUSCLE_CODE[exercise.primaryMuscle]),
        // In the library's muscle order, the order the database reads them back in.
        quote(
          exercise.secondaryMuscles
            .map((muscle) => MUSCLE_CODE[muscle])
            .sort()
            .join(''),
        ),
        quote(TYPE_CODE[exercise.type]),
        exercise.isCompound ? '1' : '0',
      ].join(',')})`,
  );
  const table = (name, codes) =>
    `\`${name}\`(\`code\`, \`value\`) AS (VALUES ${Object.entries(codes)
      .map(([value, code]) => `('${code}','${value}')`)
      .join(',')})`;
  const sql = [
    '-- Generated by scripts/exercise-dataset/build-seed.js: do not edit by hand.',
    '-- Exercise data from github.com/hasaneyldrm/exercises-dataset (MIT License, (c) 2026 Hasan Emir Yildirim).',
    '-- Names, muscles and equipment only; the dataset media (Gym visual) is not used.',
    `-- ${records.length} records: ${added.length} added, ${duplicates} duplicates of the library or of each other,`,
    `-- ${skippedTotal} that Teras cannot log (cardio, balls, rollers).`,
    '-- A name the library already holds (built in, or a custom one made before this ran) is not added again.',
    '-- Rows: id, name, equipment code, primary muscle code, secondary muscle codes, type code, compound.',
    'WITH',
    `${table('muscle', MUSCLE_CODE)},`,
    `${table('equipment', EQUIPMENT_CODE)},`,
    `${table('kind', TYPE_CODE)},`,
    '`dataset`(`id`, `name`, `equipment`, `primary`, `secondary`, `kind`, `compound`) AS (VALUES',
    values.join(',\n'),
    ')',
    'INSERT OR IGNORE INTO `exercises` (`id`, `user_id`, `created_at`, `updated_at`, `deleted_at`, `dirty`, `name`, `equipment`, `primary_muscle`, `secondary_muscles`, `type`, `is_compound`, `is_custom`)',
    `SELECT d.\`id\`, NULL, '${SEEDED_AT}', '${SEEDED_AT}', NULL, 0, d.\`name\`, e.\`value\`, m.\`value\`,`,
    '  (SELECT json_group_array(`value`) FROM `muscle` WHERE instr(d.`secondary`, `code`) > 0),',
    '  k.`value`, d.`compound`, 0',
    'FROM `dataset` AS d',
    'JOIN `equipment` AS e ON e.`code` = d.`equipment`',
    'JOIN `muscle` AS m ON m.`code` = d.`primary`',
    'JOIN `kind` AS k ON k.`code` = d.`kind`',
    'WHERE NOT EXISTS (SELECT 1 FROM `exercises` WHERE lower(`exercises`.`name`) = lower(d.`name`) AND `exercises`.`deleted_at` IS NULL);',
    '',
  ].join('\n');
  fs.writeFileSync(OUTPUT, sql);
  process.stdout.write(
    `${records.length} records -> ${added.length} added, ${duplicates} duplicates, skipped ${JSON.stringify(skipped)}\n` +
      `wrote ${path.relative(ROOT, OUTPUT)} (${Math.round(sql.length / 1024)} KB)\n`,
  );
}

main();
